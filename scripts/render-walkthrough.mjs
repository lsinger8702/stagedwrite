import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { verifyTrace, zipFiles, verifyArtifacts } from './walkthrough-artifacts.mjs';
const root=dirname(dirname(fileURLToPath(import.meta.url)));
const tracePath=join(root,'docs/examples/publish-resume-trace.json');
const raw=readFileSync(tracePath,'utf8');
const trace=JSON.parse(raw);
const checking=process.argv.includes('--check');
if(checking)verifyTrace(trace,JSON.parse(readFileSync(join(root,'dist/walkthrough-raw.json'),'utf8')));
const source=p=>({path:p,text:readFileSync(join(root,p),'utf8')});
const bundle={trace,traceSha256:createHash('sha256').update(raw).digest('hex'),sources:{fixture:source('examples/fixtures/project-tasks-managed.ts'),example:source('examples/publish-and-resume.ts'),launcher:source('scripts/run-walkthrough.mjs')}};
const template=readFileSync(join(root,'scripts/walkthrough-template.html'),'utf8');
if(!template.includes('__BUNDLE__'))throw new Error('Missing data placeholder');
const html=template.replace('__BUNDLE__',Buffer.from(JSON.stringify(bundle)).toString('base64'));
const output=join(root,'docs/examples/publish-resume.html');
const steps=trace.steps;
const markdown=`# 当前协议的真实输入输出\n\n实际执行库、SQLite 与断言；远端是 Mock，无 HTTP/LLM 调用。运行时间 ${trace.recordedAt}。\n\n[交互 HTML](publish-resume.html) · [完整 JSON](publish-resume-trace.json) · [源码](../../examples/publish-and-resume.ts)\n\n运行 npm run demo:html 重新生成。\n\n${steps.map((s, i) => `## ${i + 1}. ${s.method}\n\n${s.note}\n\n输入：\n\n\`\`\`json\n${JSON.stringify(s.input, null, 2)}\n\`\`\`\n\n输出：\n\n\`\`\`json\n${JSON.stringify(s.output, null, 2)}\n\`\`\`\n\n远端调用：\n\n\`\`\`json\n${JSON.stringify(s.remoteCalls, null, 2)}\n\`\`\``).join("\n\n")}\n`;
const files=[['publish-resume-trace.json',raw],['publish-resume-walkthrough.md',markdown],['publish-resume.html',html]];
const zip=zipFiles([['stagedwrite.html',html],['actual-input-output.json',raw],['walkthrough.md',markdown]]);
files.push(['stagedwrite-walkthrough.zip',zip]);
if(checking)verifyArtifacts(files,name=>readFileSync(join(root,'docs/examples',name)));
else for(const [name,data] of files)writeFileSync(join(root,'docs/examples',name),data);
console.log(JSON.stringify({output,recordedAt:trace.recordedAt,calls:trace.steps.length,diagnostics:trace.steps.find(s=>s.output?.status==='blocked').output.diagnostics.length,bytes:Buffer.byteLength(html),traceSha256:bundle.traceSha256}));
